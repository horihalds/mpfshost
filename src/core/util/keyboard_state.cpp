    std::vector<std::uint8_t> decodeKeyboardState(std::span<const std::byte> state)
    {
        std::vector<std::uint8_t> pressed;
        if (state.size() < kKeyboardStateBytes)
        {
            return pressed;
        }

        for (std::size_t virtualKey = 0; virtualKey < kKeyboardVirtualKeyCount; ++virtualKey)
        {
            const auto byte = std::to_integer<std::uint8_t>(state[virtualKey / 4]);
            const auto bit  = static_cast<std::uint8_t>(1u << ((virtualKey % 4) * 2));
            if ((byte & bit) != 0)
            {
                pressed.push_back(static_cast<std::uint8_t>(virtualKey));
            }
        }
        return pressed;
    }

    std::string_view virtualKeyName(std::uint8_t virtualKey) noexcept
    {
        const char* name = kVirtualKeyNames[virtualKey];
        return name == nullptr ? std::string_view {} : std::string_view {name};
    }
